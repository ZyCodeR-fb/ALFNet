def render():
    """Every file this generator owns, as {path: text}. Deterministic."""
    files = {}
    for dataset in DATASETS:
        fact = facts(dataset)
        files[OUTPUT / f"{dataset}_ALFNet.yaml"] = alfnet_config(fact)
        files[OUTPUT / f"{dataset}_MoGERNN.yaml"] = mogernn_config(fact)
        files[EXPERTS / f"{dataset}_ALFGraph.yaml"] = alfgraph_config(fact)
        files[EXPERTS / f"{dataset}_ALFTemporal.yaml"] = alftemporal_config(fact)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify the files on disk are byte-identical")
    arguments = parser.parse_args()

    files = render()
    if arguments.check:
        stale = []
        for path, text in sorted(files.items()):
            if not path.exists():
                stale.append(f"{path.relative_to(ROOT)}: missing")
            elif path.read_text("utf-8") != text:
                stale.append(f"{path.relative_to(ROOT)}: differs from the generator")
        if stale:
            print("\n".join(stale))
            return 1
        print(f"{len(files)} v4 configs are byte-identical to the generator")
        return 0
    EXPERTS.mkdir(parents=True, exist_ok=True)
    for path, text in sorted(files.items()):
        path.write_text(text, "utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
