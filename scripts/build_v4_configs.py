#!/usr/bin/env python
"""Generate the eight v4 development-base configs from the frozen manifests.

Hand-copied twins drift. The v3 tree already shows how: every PEMS08 config
declares `input_features: v` while the PEMS08 payload's target is flow, because
the file was copied from PEMS-BAY and only the dataset block was edited. Nothing
downstream noticed, since both are one channel wide.

So the per-dataset facts are *read* here -- payload path, unseen path, target
name and channel, node count, layout algorithm and `spa_patchsize` -- from
`configs/paper/v4_data_manifests/<DS>_run_manifest.json`, and everything else is
one template per model. `--check` regenerates into memory and diffs, so a config
edited by hand fails the audit instead of quietly becoming the truth.

These are **development_base** configs. They inherit each model's already-
validated capacity and optimiser settings unchanged and are not the outcome of
any v4 search; they are not a confirmatory freeze.

    python scripts/build_v4_configs.py            # write
    python scripts/build_v4_configs.py --check    # verify byte-identical
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from lib import lcbt_v4  # noqa: E402

MANIFESTS = ROOT / "configs/paper/v4_data_manifests"
OUTPUT = ROOT / "configs/paper/v4"
EXPERTS = OUTPUT / "experts"
# Five datasets: three flow (q) and two speed (v). The two units are never
# averaged together downstream -- an "avg_mae" over flow and speed would be
# a number with no unit.
DATASETS = ("PEMS03", "PEMS04", "PEMS08", "METRLA", "PEMSBAY")

# Per model, not per dataset: each keeps the capacity and optimiser settings it
# already ran under. Nothing here was chosen by a v4 measurement.
#
# `batch_size: 64` for both is a **configuration provenance correction**, not a
# tuning decision. The v3 ALFNet YAMLs declare 16, but that value never took
# effect: `configs/paper/final_runs.json` is frozen at `batch_size: 64` and
# passes it on every run, and the run it produced records the truth --
# `outputs/ALFNet/alfnet-pems08-s32/checkpoints/training_summary.json` has
# `efficiency.batch_size = 64`, `optimizer_steps_per_epoch = 140` and
# `train_samples_per_epoch = 8905` (8905 / 64 -> 140 steps). Generating v4 from
# the YAML default rather than the launcher's override gave ALFNet a batch size
# no v3 experiment ever used, and a four-fold change in optimiser steps per
# epoch with it.
#
# No learning rate moves with it. Linear scaling would be a tuning choice, and
# 5e-5 / 1e-3 are the rates the v3 runs actually used at batch 64.
MODEL_SETTINGS = {
    "ALFNet": {"batch_size": 64, "lr": 0.00005, "model_variant": "gs_v4"},
    "MoGERNN": {"batch_size": 64, "lr": 0.001, "model_variant": "mg_v4"},
}

HEADER = """# GENERATED by scripts/build_v4_configs.py -- do not edit; edit the generator.
#
# Status: development_base. Each model keeps the capacity and optimiser settings
# it already ran under, and nothing here was selected by a v4 measurement. This
# is NOT a confirmatory freeze.
#
# Every dataset-specific value below is read from
# configs/paper/v4_data_manifests/{dataset}_run_manifest.json:
#   target {target!r} at channel {channel}, {nodes} nodes,
#   layout {layout} with spa_patchsize {patch}.
"""


def manifest(dataset):
    return json.loads((MANIFESTS / f"{dataset}_run_manifest.json").read_text("utf-8"))


def facts(dataset):
    payload = manifest(dataset)
    return {
        "dataset": dataset,
        "payload": payload["payload"]["path"],
        "unseen": payload["unseen"]["path"],
        "target": payload["target"]["name"],
        "channel": int(payload["target"]["channel"]),
        "nodes": int(payload["propagation_graph"]["shape"][0]),
        "layout": payload["layout"]["algorithm"],
        "patch": int(payload["layout"]["spa_patchsize"]),
        "recur_times": int(payload["layout"]["recur_times"]),
    }


def _header(fact):
    return HEADER.format(**fact)


def _dataset_block(fact, indent=""):
    return f"""{indent}dloader_name: {fact['dataset']}
{indent}data_path: ./{fact['payload']}
{indent}unknown_nodes_path: ./{fact['unseen']}
{indent}input_len: 12
{indent}pred_len: 12
{indent}look_back: 0
{indent}slide_step: 12
{indent}input_features: {fact['target']}
{indent}target_features: {fact['target']}
{indent}freq: min
"""


def _v4_lifecycle_block(lifecycle_features):
    flags = "true" if lifecycle_features else "false"
    return f"""lifecycle:
  # ALFNet's method inputs. MoGERNN reads only base_visible_input, so it
  # declares them off rather than carrying a feature it must never consume.
  train_for_async_lifecycle: {flags}
  lifecycle_role_features: {flags}
  lifecycle_history_age_feature: {flags}
  lifecycle_observation_mask_feature: {flags}
  lifecycle_age_mode: state_duration
  lifecycle_training_strategy: {lcbt_v4.STRATEGY}
  lcbt_protocol_seed: 2026
  lcbt_validation_seed: 12026
  # The v4 time split. args.py refuses any other value under this strategy.
  lcbt_train_end_ratio: {lcbt_v4.TRAIN_END_RATIO:.2f}
  lcbt_val_end_ratio: {lcbt_v4.VAL_END_RATIO:.2f}
  lcbt_test_start_ratio: {lcbt_v4.TEST_START_RATIO:.2f}
  lcbt_scaler_end_ratio: {lcbt_v4.SCALER_END_RATIO:.2f}
  lcbt_zero_history_ratio: {lcbt_v4.SCENARIO_RATIOS['lcbt_zero_history_ratio']:.2f}
  lcbt_steady_ratio: {lcbt_v4.SCENARIO_RATIOS['lcbt_steady_ratio']:.2f}
  lcbt_join_ratio: {lcbt_v4.SCENARIO_RATIOS['lcbt_join_ratio']:.2f}
  lcbt_fault_ratio: {lcbt_v4.SCENARIO_RATIOS['lcbt_fault_ratio']:.2f}
"""


