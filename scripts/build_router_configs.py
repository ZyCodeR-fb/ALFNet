"""Generate the differentiable-router candidate configs from their base files.

Eight files, and every one of them is one key away from something that already
exists. Writing them by hand invites the two mistakes the tests then have to
catch: a candidate that quietly differs from `fg1` in more than the router, and
a PEMS-BAY twin that drifts from its METR-LA counterpart. Deriving them makes
both properties true by construction.

    ALFGraph  METRLA_alfgraph_k1.yaml      -> METRLA_alfgraph_{soft,st1,static}.yaml
              PEMSBAY_alfgraph_k1.yaml     -> PEMSBAY_alfgraph_{soft,st1,static}.yaml
              PEMS08_alfgraph_k1.yaml      -> PEMS08_alfgraph_{soft,st1,static}.yaml
    ALFNet    fg1.yaml                     -> gs.yaml, g1.yaml, gm.yaml
              fg1_bay.yaml                 -> gs_bay.yaml, g1_bay.yaml, gm_bay.yaml
              fg1_p8.yaml                  -> gs_p8.yaml, g1_p8.yaml, gm_p8.yaml

`gs` is the mainline; `g1` and `gm` are routing ablations kept for the paper's
ablation table and are not a live design search.

Run:  python scripts/build_router_configs.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GRAPH = ROOT / "configs" / "ALFGraph"
ALFNET = ROOT / "configs" / "ALFNet"

# variant -> (router mode, ALFGraph file suffix)
CANDIDATES = {
    "gs": ("soft", "soft"),
    "g1": ("st_top1", "st1"),
    # The control arm: one learned mixture for every node, no lifecycle input.
    # It answers "does conditioning the mixture on lifecycle state earn its
    # keep?", which measurement alone could not settle -- the trained `gs`
    # router moves the forecast by 0.74% against an exactly uniform gate, real
    # but the same order as the gaps between candidates.
    "gm": ("static", "static"),
}

HEADER = """\
# GENERATED by scripts/build_router_configs.py -- edit the base config instead.
#
# {why}
"""

GRAPH_WHY = (
    "Differs from {base} in `moge_router_mode` alone. At the shipped\n"
    "# `moge_top_k: 1` the default noisy top-k router is not reachable from the\n"
    "# forecast loss at all: a one-column Softmax is identically 1.0 with zero\n"
    "# derivative, so `w_gate` is trained only by the load-balance prior. See\n"
    "# layers/lifecycle_moge.py for the measurements."
)

ALFNET_WHY = (
    "Differs from {base} in the graph expert's config path alone; that file in\n"
    "# turn differs from its own base in `moge_router_mode` alone. Nothing else\n"
    "# about the model, the objective or the protocol moves."
)


def _rewrite(lines, replacements):
    out = []
    for line in lines:
        for needle, value in replacements.items():
            if line.startswith(needle):
                line = value
                break
        out.append(line)
    return out


def build_graph_config(base_name, suffix, mode):
    base = GRAPH / base_name
    lines = base.read_text(encoding="utf-8").splitlines()
    variant = f"alf_gsd_{suffix}"
    lines = _rewrite(lines, {"  model_variant:": f"  model_variant: {variant}"})
    # `moge_router_mode` sits next to the other moge_* keys so the block reads
    # as one unit rather than an afterthought appended to the file.
    out = []
    for line in lines:
        out.append(line)
        if line.strip().startswith("moge_top_k:"):
            out.append(f"    moge_router_mode: {mode}")
    target = GRAPH / base_name.replace("_k1.yaml", f"_{suffix}.yaml")
    body = HEADER.format(why=GRAPH_WHY.format(base=base_name)) + "\n".join(out) + "\n"
    target.write_text(body, encoding="utf-8")
    return target


def build_alfnet_config(base_name, variant, graph_config):
    base = ALFNET / base_name
    lines = base.read_text(encoding="utf-8").splitlines()
    lines = _rewrite(
        lines,
        {
            "  model_variant:": f"  model_variant: {variant}",
            "      config_path: ./configs/ALFGraph/": f"      config_path: {graph_config}",
        },
    )
    target = ALFNET / f"{variant}.yaml"
    body = HEADER.format(why=ALFNET_WHY.format(base=base_name)) + "\n".join(lines) + "\n"
    target.write_text(body, encoding="utf-8")
    return target


def main():
    written = []
    for variant, (mode, suffix) in CANDIDATES.items():
        for dataset, graph_base, alfnet_base, name in (
            ("METRLA", "METRLA_alfgraph_k1.yaml", "fg1.yaml", variant),
            ("PEMSBAY", "PEMSBAY_alfgraph_k1.yaml", "fg1_bay.yaml", f"{variant}_bay"),
            ("PEMS08", "PEMS08_alfgraph_k1.yaml", "fg1_p8.yaml", f"{variant}_p8"),
        ):
            graph_target = build_graph_config(graph_base, suffix, mode)
            written.append(graph_target)
            written.append(
                build_alfnet_config(
                    alfnet_base,
                    name,
                    f"./configs/ALFGraph/{graph_target.name}",
                )
            )
    for path in written:
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
