#!/usr/bin/env python
"""Generate the bounded PEMS08 seed-32 LF/SUP candidate configs.

No candidate is selected here and this script never trains.  The fixed set is
BASE, LF, SUP and LF+SUP for ALFNet, plus the unchanged MoGERNN control.  LF's
0.05 coefficient is intentionally small and fixed before candidate results are
opened; SUP changes only the propagation inventory.
"""

import argparse
from copy import deepcopy
from pathlib import Path

from omegaconf import OmegaConf

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "configs/paper/v4"
OUTPUT = ROOT / "configs/paper/v4_candidates/PEMS08"
LF_WEIGHT = 0.05

HEADER = (
    "# GENERATED by scripts/build_v4_lf_sup_candidates.py -- do not edit.\n"
    "# Development-only PEMS08 seed-32 candidate; test split is forbidden.\n"
)


def _plain(path):
    return OmegaConf.to_container(OmegaConf.load(path), resolve=True)


def _render(payload):
    return HEADER + OmegaConf.to_yaml(OmegaConf.create(payload), resolve=True)


def generated():
    graph_base = _plain(SOURCE / "experts/PEMS08_ALFGraph.yaml")
    graph_sup = deepcopy(graph_base)
    graph_sup["runtime"]["model_variant"] = "alf_gsd_soft_sup_v1"
    graph_sup["family"]["recipe"]["moge_support_set"] = \
        "distinct_multiscale_v1"
    paths = {
        OUTPUT / "experts/PEMS08_ALFGraph_legacy.yaml": _render(graph_base),
        OUTPUT / "experts/PEMS08_ALFGraph_sup.yaml": _render(graph_sup),
    }

    base = _plain(SOURCE / "PEMS08_ALFNet.yaml")
    for name, lf, sup in (
        ("BASE", False, False),
        ("LF", True, False),
        ("SUP", False, True),
        ("LF_SUP", True, True),
    ):
        candidate = deepcopy(base)
        candidate["runtime"]["model_variant"] = f"gs_v4_{name.lower()}"
        candidate["family"]["recipe"]["forecast_safe_relative_weight"] = \
            LF_WEIGHT if lf else 0.0
        graph_name = "PEMS08_ALFGraph_sup.yaml" if sup else \
            "PEMS08_ALFGraph_legacy.yaml"
        candidate["family"]["experts"]["graph"]["config_path"] = \
            f"./configs/paper/v4_candidates/PEMS08/experts/{graph_name}"
        paths[OUTPUT / f"{name}_ALFNet.yaml"] = _render(candidate)

    control = _plain(SOURCE / "PEMS08_MoGERNN.yaml")
    control["runtime"]["model_variant"] = "mg_v4_candidate_control"
    paths[OUTPUT / "CONTROL_MoGERNN.yaml"] = _render(control)
    return paths


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    failed = []
    for path, body in generated().items():
        if args.check:
            if not path.exists() or path.read_text("utf-8") != body:
                failed.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body, "utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if failed:
        raise SystemExit("candidate configs differ: " + ", ".join(failed))


if __name__ == "__main__":
    main()
